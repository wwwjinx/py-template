-- Postgres 空库初始化脚本：建表 + 种子数据（超管 / 部门 / 角色 / 菜单 / 字典）。
-- 与 app/models、app/seed 对齐。启动不会自动执行。
-- 用于空库；已有库请用 `uv run python -m app.seed`（init_db + seed，已存在则跳过）。
-- 默认账号 admin / admin123。
--
-- 示例：
--   psql -h 127.0.0.1 -U postgres -d your_db -f sql/init.sql

BEGIN;

-- sys_dept

CREATE TABLE sys_dept (
    dept_id BIGINT GENERATED BY DEFAULT AS IDENTITY, 
    parent_id BIGINT, 
    ancestors VARCHAR(50), 
    dept_name VARCHAR(30), 
    order_num INTEGER, 
    leader VARCHAR(20), 
    phone VARCHAR(11), 
    email VARCHAR(50), 
    status VARCHAR(1), 
    del_flag VARCHAR(1), 
    create_by VARCHAR(64), 
    create_time TIMESTAMP WITH TIME ZONE, 
    update_by VARCHAR(64), 
    update_time TIMESTAMP WITH TIME ZONE, 
    PRIMARY KEY (dept_id)
);

-- sys_user

CREATE TABLE sys_user (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY, 
    dept_id BIGINT, 
    user_name VARCHAR(30) NOT NULL, 
    nick_name VARCHAR(30) NOT NULL, 
    user_type VARCHAR(2), 
    email VARCHAR(50), 
    phonenumber VARCHAR(11), 
    sex VARCHAR(1), 
    avatar VARCHAR(100), 
    time_zone VARCHAR(64) NOT NULL, 
    password VARCHAR(100), 
    status VARCHAR(1), 
    del_flag VARCHAR(1), 
    login_ip VARCHAR(128), 
    login_date TIMESTAMP WITH TIME ZONE, 
    pwd_update_date TIMESTAMP WITH TIME ZONE, 
    create_by VARCHAR(64), 
    create_time TIMESTAMP WITH TIME ZONE, 
    update_by VARCHAR(64), 
    update_time TIMESTAMP WITH TIME ZONE, 
    remark VARCHAR(500), 
    PRIMARY KEY (user_id)
);

-- sys_role

CREATE TABLE sys_role (
    role_id BIGINT GENERATED BY DEFAULT AS IDENTITY, 
    role_name VARCHAR(30) NOT NULL, 
    role_key VARCHAR(100) NOT NULL, 
    role_sort INTEGER NOT NULL, 
    data_scope VARCHAR(1), 
    menu_check_strictly SMALLINT, 
    dept_check_strictly SMALLINT, 
    status VARCHAR(1) NOT NULL, 
    del_flag VARCHAR(1), 
    create_by VARCHAR(64), 
    create_time TIMESTAMP WITH TIME ZONE, 
    update_by VARCHAR(64), 
    update_time TIMESTAMP WITH TIME ZONE, 
    remark VARCHAR(500), 
    PRIMARY KEY (role_id)
);

-- sys_menu

CREATE TABLE sys_menu (
    menu_id BIGINT GENERATED BY DEFAULT AS IDENTITY, 
    menu_name VARCHAR(50) NOT NULL, 
    parent_id BIGINT, 
    order_num INTEGER, 
    path VARCHAR(200), 
    component VARCHAR(255), 
    query VARCHAR(255), 
    route_name VARCHAR(50), 
    is_frame INTEGER, 
    is_cache INTEGER, 
    menu_type VARCHAR(1), 
    visible VARCHAR(1), 
    status VARCHAR(1), 
    perms VARCHAR(100), 
    icon VARCHAR(100), 
    create_by VARCHAR(64), 
    create_time TIMESTAMP WITH TIME ZONE, 
    update_by VARCHAR(64), 
    update_time TIMESTAMP WITH TIME ZONE, 
    remark VARCHAR(500), 
    PRIMARY KEY (menu_id)
);

-- sys_user_role

CREATE TABLE sys_user_role (
    user_id BIGINT NOT NULL, 
    role_id BIGINT NOT NULL, 
    PRIMARY KEY (user_id, role_id)
);

-- sys_role_menu

CREATE TABLE sys_role_menu (
    role_id BIGINT NOT NULL, 
    menu_id BIGINT NOT NULL, 
    PRIMARY KEY (role_id, menu_id)
);

-- sys_role_dept

CREATE TABLE sys_role_dept (
    role_id BIGINT NOT NULL, 
    dept_id BIGINT NOT NULL, 
    PRIMARY KEY (role_id, dept_id)
);

-- sys_dict_type

CREATE TABLE sys_dict_type (
    dict_id BIGINT GENERATED BY DEFAULT AS IDENTITY, 
    dict_name VARCHAR(100), 
    dict_type VARCHAR(100), 
    status VARCHAR(1), 
    create_by VARCHAR(64), 
    create_time TIMESTAMP WITH TIME ZONE, 
    update_by VARCHAR(64), 
    update_time TIMESTAMP WITH TIME ZONE, 
    remark VARCHAR(500), 
    PRIMARY KEY (dict_id), 
    UNIQUE (dict_type)
);

-- sys_dict_data

CREATE TABLE sys_dict_data (
    dict_code BIGINT GENERATED BY DEFAULT AS IDENTITY, 
    dict_sort INTEGER, 
    dict_label VARCHAR(100), 
    dict_value VARCHAR(100), 
    dict_type VARCHAR(100), 
    css_class VARCHAR(100), 
    list_class VARCHAR(100), 
    is_default VARCHAR(1), 
    status VARCHAR(1), 
    create_by VARCHAR(64), 
    create_time TIMESTAMP WITH TIME ZONE, 
    update_by VARCHAR(64), 
    update_time TIMESTAMP WITH TIME ZONE, 
    remark VARCHAR(500), 
    PRIMARY KEY (dict_code)
);

-- sys_oper_log

CREATE TABLE sys_oper_log (
    oper_id BIGINT GENERATED BY DEFAULT AS IDENTITY, 
    title VARCHAR(50), 
    business_type INTEGER, 
    method VARCHAR(100), 
    request_method VARCHAR(10), 
    operator_type INTEGER, 
    oper_name VARCHAR(50), 
    dept_name VARCHAR(50), 
    oper_url VARCHAR(255), 
    oper_ip VARCHAR(128), 
    oper_location VARCHAR(255), 
    oper_param VARCHAR(2000), 
    json_result VARCHAR(2000), 
    status INTEGER, 
    error_msg VARCHAR(2000), 
    oper_time TIMESTAMP WITH TIME ZONE, 
    cost_time BIGINT, 
    PRIMARY KEY (oper_id)
);

-- sys_logininfor

CREATE TABLE sys_logininfor (
    info_id BIGINT GENERATED BY DEFAULT AS IDENTITY, 
    user_name VARCHAR(50), 
    ipaddr VARCHAR(128), 
    login_location VARCHAR(255), 
    browser VARCHAR(50), 
    os VARCHAR(50), 
    status VARCHAR(1), 
    msg VARCHAR(255), 
    login_time TIMESTAMP WITH TIME ZONE, 
    PRIMARY KEY (info_id)
);

-- sys_file

CREATE TABLE sys_file (
    file_id BIGINT GENERATED BY DEFAULT AS IDENTITY, 
    original_filename VARCHAR(255), 
    file_name VARCHAR(500), 
    new_file_name VARCHAR(255), 
    url VARCHAR(1000), 
    file_suffix VARCHAR(32), 
    content_type VARCHAR(128), 
    size BIGINT, 
    del_flag VARCHAR(1), 
    create_by VARCHAR(64), 
    create_time TIMESTAMP WITH TIME ZONE, 
    PRIMARY KEY (file_id)
);

-- test

CREATE TABLE test (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY (INCREMENT BY 1 START WITH 1 MINVALUE 1 MAXVALUE 2147483647 CACHE 1 NO CYCLE), 
    text VARCHAR(255), 
    PRIMARY KEY (id)
);

